/*
 * tb_pcie_gen6_g1.sv -- executable self-checking top-level testbench for G1.
 *
 * PURPOSE:
 *   Exercise the RTL v0.3 FLIT codec prototype through its public top-level
 *   ready/valid interface. Independent Python-generated expected full FLITs
 *   provide the oracle; a DUT encoder-to-DUT decoder loopback alone is NOT
 *   an adequate correctness check.
 *
 * TESTS:
 *   1. RESET / link guard / Gen1..Gen6 status / illegal widths & modes;
 *   2. TLP packer length boundaries and diagnostics;
 *   3. TX handshake, byte-for-byte FLIT check, backpressure stability;
 *   4. RX good / one-byte FEC-correctable / two-byte bad / drop count;
 *   5. Local engineering CSR read-write and reset;
 *   6. Link-down TX/RX buffered frame flush without global reset.
 *
 * NON-GOALS:
 *   No UVM, Root Complex peer, real transaction parsing, DLL replay,
 *   LTSSM, PHY PIPE, Gen1..Gen5 non-FLIT, electrical PAM4, compliance.
 *
 * EXECUTION:
 *   make tb-smoke       (requires Verilator >=5)
 *   make tb-model       (independent Python reference, not HDL)
 * Vectors:
 *   build/tb/vectors/*.hex generated by tb/python/gen_vectors.py.
 *   Each hex literal stores byte 0 in the least significant bits.
 */
`timescale 1ns/1ps
module tb_pcie_gen6_g1;
  localparam int CASES = 8;
  logic clk = 1'b0;
  always #5 clk = ~clk;
  logic rst_n=0;
  logic phy_l0=0, phy_flit_enabled=0;
  logic [2:0] phy_gen=3'd6;
  logic [4:0] phy_width=5'd4;
  logic flit_link_ready, unsupported_nonflit, invalid_negotiation;
  logic csr_rd_en=0, csr_wr_en=0;
  logic [7:0] csr_addr='0;
  logic [31:0] csr_wdata='0, csr_rdata;
  logic csr_rvalid;
  logic tx_tlp_valid=0, tx_tlp_ready;
  logic [1887:0] tx_tlp_bytes='0;
  logic [5:0] tx_tlp_dw_count='0;
  logic [47:0] tx_dlp='0;
  logic tx_length_error;
  logic phy_tx_flit_valid, phy_tx_flit_ready=0;
  logic [2047:0] phy_tx_flit;
  logic phy_rx_flit_valid=0, phy_rx_flit_ready;
  logic [2047:0] phy_rx_flit='0;
  logic rx_tlp_area_valid, rx_tlp_area_ready=0;
  logic [1887:0] rx_tlp_area;
  logic [47:0] rx_dlp;
  logic rx_drop_pulse, rx_fec_corrected_pulse;
  logic [31:0] rx_crc_error_count;

  logic [2047:0] golden [0:CASES-1];
  logic [1887:0] raw_tlps [0:CASES-1];
  logic [47:0] dlps [0:CASES-1];
  logic [5:0] lengths [0:CASES-1];
  int passed=0;
  int seed=17;

  pcie_gen6_controller_top dut (.*);

  /* Fail fast: every check is an RTL-visible invariant with a specific name. */
  task automatic expect_true(input bit condition,input string testname);
    if (!condition) $fatal(1, "FAIL %s at cycle time %0t",testname,$time);
    passed=passed+1;
  endtask

  /* CSR is local engineering register interface, NOT PCIe config access. */
  task automatic csr_read(input logic [7:0] addr,
                          input logic [31:0] expected,
                          input string testname);
    @(negedge clk);
    csr_rd_en=1; csr_addr=addr;
    @(posedge clk); #1;
    expect_true(csr_rvalid && csr_rdata===expected,testname);
    @(negedge clk);
    csr_rd_en=0;
  endtask

  task automatic csr_write(input logic [7:0] addr,
                           input logic [31:0] value);
    @(negedge clk);
    csr_wr_en=1; csr_addr=addr; csr_wdata=value;
    @(posedge clk); #1;
    @(negedge clk); csr_wr_en=0;
  endtask

  /* Exercise every supported width at every reported speed and rejected modes.
   * External PHY status is directly driven: there is no real LTSSM here. */
  task automatic check_link_guard;
    logic [4:0] widths [0:4];
    widths[0]=1; widths[1]=2; widths[2]=4; widths[3]=8; widths[4]=16;
    @(negedge clk); phy_l0=0; phy_flit_enabled=1;
    #1; expect_true(!flit_link_ready,"L0 required");
    for (int gen=1; gen<=6; gen++) begin
      for (int w=0; w<5; w++) begin
        @(negedge clk);
        phy_l0=1; phy_flit_enabled=1;
        phy_gen=3'(gen); phy_width=widths[w];
        #1; expect_true(flit_link_ready && !invalid_negotiation,
                        "Gen1..Gen6 valid FLIT status/width");
      end
    end
    @(negedge clk); phy_width=3;
    #1; expect_true(!flit_link_ready && invalid_negotiation,
                   "reject non-power-of-two width");
    @(negedge clk); phy_width=4; phy_gen=0;
    #1; expect_true(!flit_link_ready && invalid_negotiation,"reject Gen0");
    @(negedge clk); phy_gen=7;
    #1; expect_true(!flit_link_ready && invalid_negotiation,"reject Gen7");
    @(negedge clk); phy_gen=6; phy_flit_enabled=0;
    #1; expect_true(!flit_link_ready && invalid_negotiation,
                   "Gen6 requires FLIT");
    @(negedge clk); phy_gen=5;
    #1; expect_true(!flit_link_ready && unsupported_nonflit &&
                   !invalid_negotiation,"non-FLIT lower generations unsupported");
    @(negedge clk);
    phy_gen=6; phy_width=4; phy_flit_enabled=1; phy_l0=1;
    #1; expect_true(flit_link_ready,"restore Gen6 FLIT link");
  endtask

  task automatic test_invalid_lengths;
    @(negedge clk);
    tx_tlp_valid=1; tx_tlp_dw_count=0; tx_tlp_bytes='0;
    #1; expect_true(tx_length_error && !tx_tlp_ready,"reject 0DW");
    @(negedge clk); tx_tlp_dw_count=60;
    #1; expect_true(tx_length_error && !tx_tlp_ready,"reject 60DW");
    @(negedge clk); tx_tlp_dw_count=63;
    #1; expect_true(tx_length_error && !tx_tlp_ready,"reject 63DW");
    @(negedge clk); tx_tlp_valid=0;
    #1; expect_true(!tx_length_error,"length error requires valid input");
  endtask

  /* TX stimulus waits for a real ready/valid handshake. Keep PHY stalled,
   * compare full encoded bytes against Python, then verify stable holding. */
  task automatic test_tx_frame(input int idx);
    logic [2047:0] held;
    @(negedge clk);
    phy_tx_flit_ready=0;
    tx_tlp_bytes=raw_tlps[idx];
    tx_tlp_dw_count=lengths[idx];
    tx_dlp=dlps[idx];
    tx_tlp_valid=1;
    #1;
    expect_true(tx_tlp_ready,"TX entry ready");
    @(posedge clk); #1;
    expect_true(phy_tx_flit_valid,"TX frame enqueued");
    expect_true(phy_tx_flit===golden[idx],"TX independent full FLIT oracle");
    held=phy_tx_flit;
    @(negedge clk);
    // A second request must not be accepted while the single-entry TX
    // holding register is full and its outgoing frame is stalled.
    tx_tlp_bytes=raw_tlps[(idx+1)%CASES];
    tx_tlp_dw_count=lengths[(idx+1)%CASES];
    tx_tlp_valid=1;
    #1; expect_true(!tx_tlp_ready,"TX backpressure propagates to source");
    tx_tlp_valid=0;
    repeat(3) begin
      @(posedge clk); #1;
      expect_true(phy_tx_flit_valid && phy_tx_flit===held,
                  "TX stable under backpressure");
    end
    @(negedge clk); phy_tx_flit_ready=1;
    @(posedge clk); #1;
    expect_true(!phy_tx_flit_valid,"TX consumed exactly once");
    @(negedge clk); phy_tx_flit_ready=0;
  endtask

  /* RX injects an entire externally supplied FLIT. Corruption is applied
   * after independent Python encoding; DUT decoder is the tested component. */
  task automatic test_rx_frame(input int idx, input int err_kind);
    logic [2047:0] damaged;
    logic [1887:0] expected_tlp;
    logic [47:0] expected_dlp;
    logic [31:0] before_drop;
    damaged=golden[idx];
    if (err_kind==1) damaged[8*235 +: 8] ^= 8'hA5;
    if (err_kind==2) begin
      damaged[8*0 +: 8] ^= 8'h53;
      damaged[8*3 +: 8] ^= 8'hC1;
    end
    expected_tlp=golden[idx][1887:0];
    expected_dlp=golden[idx][1935:1888];
    before_drop=rx_crc_error_count;
    @(negedge clk);
    rx_tlp_area_ready=0;
    phy_rx_flit=damaged;
    phy_rx_flit_valid=1;
    #1; expect_true(phy_rx_flit_ready,"RX entry ready");
    @(posedge clk); #1;
    if (err_kind==2) begin
      expect_true(!rx_tlp_area_valid && rx_drop_pulse,
                  "uncorrectable frame dropped");
      expect_true(rx_crc_error_count==before_drop+1,
                  "bad frame increments diagnostic count");
    end else begin
      expect_true(rx_tlp_area_valid && !rx_drop_pulse,
                  "good/corrected RX frame delivered");
      expect_true(rx_tlp_area===expected_tlp && rx_dlp===expected_dlp,
                  "RX independent TLP+DLP oracle");
      if (err_kind==1)
        expect_true(rx_fec_corrected_pulse,"FEC correction indicated");
      else
        expect_true(!rx_fec_corrected_pulse,"clean RX no correction");
    end
    @(negedge clk); phy_rx_flit_valid=0;
    if (err_kind!=2) begin
      repeat(2) begin
        @(posedge clk); #1;
        expect_true(rx_tlp_area_valid && rx_tlp_area===expected_tlp &&
                    rx_dlp===expected_dlp,"RX stable under backpressure");
      end
      @(negedge clk); rx_tlp_area_ready=1;
      @(posedge clk); #1;
      expect_true(!rx_tlp_area_valid,"RX consumed exactly once");
      @(negedge clk); rx_tlp_area_ready=0;
    end else begin
      @(posedge clk); #1;
      expect_true(!rx_drop_pulse,"drop pulse is one cycle");
    end
  endtask

  /* Known v0.2 design defect: buffers previously survived link loss.
   * v0.3 sends a synchronous flush to each FIFO and masks valid immediately. */
  task automatic test_link_loss_flush;
    @(negedge clk);
    tx_tlp_bytes=raw_tlps[1]; tx_tlp_dw_count=lengths[1];
    tx_dlp=dlps[1]; tx_tlp_valid=1; phy_tx_flit_ready=0;
    #1; expect_true(tx_tlp_ready,"prepare queued TX");
    @(posedge clk); #1;
    expect_true(phy_tx_flit_valid,"TX occupied before link loss");
    @(negedge clk); tx_tlp_valid=0; phy_l0=0;
    #1; expect_true(!phy_tx_flit_valid && !flit_link_ready,
                   "TX output masked on link loss");
    @(posedge clk); #1; /* synchronous flush */
    @(negedge clk); phy_l0=1;
    #1; expect_true(!phy_tx_flit_valid,"no stale TX after relink");
    /* Repeat for queued RX. */
    @(negedge clk);
    phy_rx_flit=golden[2]; phy_rx_flit_valid=1; rx_tlp_area_ready=0;
    @(posedge clk); #1;
    expect_true(rx_tlp_area_valid,"RX occupied before link loss");
    @(negedge clk); phy_rx_flit_valid=0; phy_l0=0;
    #1; expect_true(!rx_tlp_area_valid,"RX output masked on link loss");
    @(posedge clk); #1;
    @(negedge clk); phy_l0=1;
    #1; expect_true(!rx_tlp_area_valid,"no stale RX after relink");
  endtask

  initial begin : watchdog
    #1000000;
    $fatal(1,"G1 HDL watchdog timeout (possible deadlock)");
  end

  initial begin : run_tests
    if (!$value$plusargs("SEED=%d",seed)) seed=17;
    $readmemh("build/tb/vectors/golden_flits.hex",golden);
    $readmemh("build/tb/vectors/raw_tlps.hex",raw_tlps);
    $readmemh("build/tb/vectors/dlp.hex",dlps);
    $readmemh("build/tb/vectors/lengths.hex",lengths);
    $dumpfile("build/tb/pcie_g1.vcd");
    $dumpvars(0,tb_pcie_gen6_g1);
    $display("G1 RTL verification started: seed=%0d",seed);
    repeat (4) @(posedge clk);
    @(negedge clk); rst_n=1;
    csr_read(8'h00,32'h50434936,"signature CSR");
    csr_read(8'h04,32'h00000200,"version CSR");
    csr_read(8'h18,32'h0000001f,"feature CSR");
    csr_write(8'h10,32'h5a59_0123);
    csr_read(8'h10,32'h5a59_0123,"scratch CSR write/read");
    check_link_guard();
    test_invalid_lengths();
    for (int i=0;i<CASES;i++) test_tx_frame(i);
    for (int i=0;i<3;i++) test_rx_frame(i,0);
    for (int i=3;i<6;i++) test_rx_frame(i,1);
    test_rx_frame(6,2);
    csr_read(8'h0c,32'h00000001,"CSR after uncorrectable RX");
    test_link_loss_flush();
    @(negedge clk); rst_n=0;
    repeat(2) @(posedge clk);
    @(negedge clk); rst_n=1;
    csr_read(8'h10,32'h00000000,"scratch reset");
    csr_read(8'h0c,32'h00000000,"drop-count reset");
    $display("ALL G1 HDL CHECKS PASSED: %0d assertions",passed);
    $finish;
  end
endmodule
